import assert from 'node:assert/strict';
import {decodeDiscoveries,discover,loadDiscoveries,saveDiscoveries,DISCOVERY_KEY} from '../src/discoveries.ts';
const records=new Map<string,string>();
const storage={getItem:(key:string)=>records.get(key)??null,setItem:(key:string,value:string)=>{records.set(key,value);}};
assert.deepEqual(loadDiscoveries(storage),[]);
const first=discover([],'smosh');
assert.equal(first.added,true);
assert.deepEqual(first.entries,['smosh']);
assert.equal(saveDiscoveries(storage,first.entries),true);
assert.deepEqual(loadDiscoveries(storage),['smosh']);
const repeat=discover(loadDiscoveries(storage),'smosh');
assert.equal(repeat.added,false);
assert.deepEqual(repeat.entries,['smosh']);
const second=discover(repeat.entries,'workshop');
assert.equal(saveDiscoveries(storage,second.entries),true);
assert.deepEqual(loadDiscoveries(storage),['smosh','workshop']);
assert.deepEqual(JSON.parse(records.get(DISCOVERY_KEY)!),{version:1,entries:['smosh','workshop']});
assert.deepEqual(decodeDiscoveries('{broken'),[]);
assert.deepEqual(decodeDiscoveries(JSON.stringify({version:2,entries:['smosh']})),[]);
assert.deepEqual(decodeDiscoveries(JSON.stringify({version:1,entries:['smosh','invalid','smosh',null,4,'atlas']})),['smosh','atlas']);
assert.deepEqual(decodeDiscoveries(JSON.stringify({version:1,entries:'smosh'})),[]);
const blocked={getItem:()=>{throw new Error('Storage denied');},setItem:()=>{throw new Error('Quota exceeded');}};
assert.deepEqual(loadDiscoveries(blocked),[]);
assert.equal(saveDiscoveries(blocked,second.entries),false);
assert.deepEqual(discover(second.entries,'future').entries,['smosh','workshop','future']);
console.log('Journal checks passed: fresh state, save/reload, duplicate discovery, multiple entries, corrupt/unsupported records, invalid IDs, denied storage, session fallback.');
